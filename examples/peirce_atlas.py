"""Generate graticule data and a pole-relative scale tile for the atlas."""

import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from peirce_mosaic import LANDMARKS, local_scale
from PIL import Image
from scipy.special import elliprf

from pyconformal.cartography import peirce_quincuncial, peirce_quincuncial_inverse


def main() -> None:
    """Prepare offline assets; split southern parallel lines across the cuts."""
    here = Path(__file__).resolve().parent
    families = []
    for latitude in range(-75, 76, 15):
        families.append(
            ("parallel", [(float(lon), latitude) for lon in np.linspace(-180, 180, 721)])
        )
    for longitude in range(-180, 180, 15):
        families.append(
            ("meridian", [(longitude, float(lat)) for lat in np.linspace(-90, 90, 361)])
        )
    paths = []
    for kind, geographic in families:
        curve: list[list[float]] = []
        for lon, lat in geographic:
            w = peirce_quincuncial(lon, lat)
            point = [round(w.real, 8), round(w.imag, 8)]
            if curve and np.hypot(point[0] - curve[-1][0], point[1] - curve[-1][1]) > 0.2:
                paths.append({"kind": kind, "points": curve})
                curve = []
            curve.append(point)
        if len(curve) > 1:
            paths.append({"kind": kind, "points": curve})
    references = []
    for lon in (-180, -135, -90, -45, 0, 45, 90, 135, 179):
        for lat in (-90, -75, -30, 0, 15, 70, 90):
            w = peirce_quincuncial(lon, lat)
            references.append([lon, lat, w.real, w.imag])
    payload = {
        "paths": paths,
        "landmarks": [list(item[:3]) for item in LANDMARKS],
        "references": references,
    }
    (here / "peirce-atlas-data.js").write_text(
        "// Generated by peirce_atlas.py; coordinates are dimensionless.\n"
        + "window.peirceAtlasData = "
        + json.dumps(payload, separators=(",", ":"), allow_nan=False)
        + ";\n",
        encoding="utf-8",
    )
    axis = -1 + 2 * (np.arange(700) + 0.5) / 700
    lon, lat = peirce_quincuncial_inverse(axis[None, :] + 1j * axis[:, None])
    ratio = local_scale(lon, lat) * (2 * float(elliprf(0, 1, 2)))
    colors = plt.get_cmap("viridis")(np.clip(np.log(ratio) / np.log(5), 0, 1), bytes=True)
    Image.fromarray(colors[::-1, :, :3]).save(here / "peirce-scale-tile.png")


if __name__ == "__main__":
    main()
